// DiseaseCodePanel — doctor's view of the patient's disease code:
//   • the AI cross-reference from registration (clearly not a diagnosis)
//   • the provisional code matched from the template
//   • confirm or change the code (each is a new ledger transaction)
//   • AI suggestion and doctor's code side by side, and the full history

import { useCallback, useEffect, useState } from 'react'
import { Bot, Check, Pencil, Loader2, AlertTriangle, Search } from 'lucide-react'
import { Card, Button, Modal, Alert } from './ui'
import DiseaseCodeHistory, { CodeStatusPill } from './DiseaseCodeHistory'

const URGENCY = {
  LOW:       { label: 'Low',       tone: 'is-ok' },
  MEDIUM:    { label: 'Medium',    tone: 'is-warn' },
  HIGH:      { label: 'High',      tone: 'is-danger' },
  EMERGENCY: { label: 'Emergency', tone: 'is-danger' },
}

const pct = (n) => `${Math.round((Number(n) || 0) * 100)}%`
const errorText = (err, fallback) => err?.response?.data?.error || (err?.response ? fallback : 'The service is not reachable. Try again.')

function Confidence({ value }) {
  return (
    <span className="inline-flex items-center gap-2 min-w-[7rem]">
      <span className="h-1.5 w-16 rounded-full bg-slate-200 overflow-hidden" aria-hidden="true">
        <span className="block h-full bg-violet-500" style={{ width: pct(value) }} />
      </span>
      <span className="text-xs tabular-nums text-slate-600">{pct(value)}</span>
    </span>
  )
}

function AiPanel({ analysis, analysisError }) {
  const ai = analysis?.aiAnalysis
  return (
    <div className="p-4 rounded-xl border border-violet-200 bg-violet-50/60">
      <p className="flex items-center gap-1.5 font-semibold text-violet-800 text-xs uppercase tracking-wide">
        <Bot size={14} /> AI cross-reference, not a diagnosis
      </p>
      {analysisError && <p role="alert" className="text-sm text-red-700 mt-2">{analysisError}</p>}
      {!analysis && !analysisError && (
        <p className="text-sm text-slate-600 mt-2">No symptoms were recorded for this patient at registration, so there is no analysis.</p>
      )}
      {analysis && (
        <div className="mt-2 space-y-3 text-sm text-slate-800">
          <p><span className="font-medium">Symptoms as reported:</span> {analysis.symptoms}</p>
          {ai?.status !== 'OK' ? (
            <p className="flex items-start gap-2 text-amber-800">
              <AlertTriangle size={15} className="mt-0.5 shrink-0" />
              The AI analysis was not available when this patient was registered{ai?.reason ? ` (${ai.reason})` : ''}. Only the template match below was recorded.
            </p>
          ) : (
            <>
              {ai.summary && <p>{ai.summary}</p>}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <div>
                  <p className="text-xs font-medium text-slate-500 uppercase tracking-wide mb-1">Probable conditions</p>
                  {ai.conditions.length === 0 ? <p className="text-slate-500">None suggested.</p> : (
                    <ul className="space-y-1">
                      {ai.conditions.map(c => (
                        <li key={c.name} className="flex items-center justify-between gap-3"><span>{c.name}</span><Confidence value={c.confidence} /></li>
                      ))}
                    </ul>
                  )}
                </div>
                <div>
                  <p className="text-xs font-medium text-slate-500 uppercase tracking-wide mb-1">Suggested codes (from the template)</p>
                  {ai.suggestedCodes.length === 0 ? <p className="text-slate-500">None suggested.</p> : (
                    <ul className="space-y-1">
                      {ai.suggestedCodes.map(c => (
                        <li key={c.code} className="flex items-center justify-between gap-3">
                          <span><span className="font-mono font-semibold">{c.code}</span> {c.name}</span><Confidence value={c.confidence} />
                        </li>
                      ))}
                    </ul>
                  )}
                </div>
              </div>
              <div className="flex flex-wrap items-center gap-x-6 gap-y-2">
                <p className="flex items-center gap-2"><span className="font-medium">Urgency:</span>
                  {URGENCY[ai.urgency] ? <span className={`status-pill ${URGENCY[ai.urgency].tone}`}>{URGENCY[ai.urgency].label}</span> : <span className="text-slate-500">not stated</span>}
                </p>
                <p><span className="font-medium">Suggested tests:</span> {ai.suggestedTests.length ? ai.suggestedTests.join(', ') : 'none'}</p>
              </div>
              <p className="text-[11px] text-slate-500">Generated by {ai.model} at registration. It has not examined the patient and may be wrong.</p>
            </>
          )}
        </div>
      )}
    </div>
  )
}

function ChangeModal({ api, visitId, current, onClose, onDone }) {
  const [query, setQuery]   = useState('')
  const [codes, setCodes]   = useState([])
  const [loading, setLoading] = useState(true)
  const [picked, setPicked] = useState(null)
  const [reason, setReason] = useState('')
  const [saving, setSaving] = useState(false)
  const [error, setError]   = useState('')

  useEffect(() => {
    let cancelled = false
    const timer = setTimeout(async () => {
      setLoading(true)
      try {
        const res = await api().get('/doctor/codes', { params: { q: query } })
        if (!cancelled) setCodes(res.data.data.codes)
      } catch (err) {
        if (!cancelled) setError(errorText(err, 'The code list could not be loaded.'))
      } finally {
        if (!cancelled) setLoading(false)
      }
    }, 250)
    return () => { cancelled = true; clearTimeout(timer) }
  }, [api, query])

  const save = async () => {
    if (!picked) return setError('Choose a code.')
    if (picked.code === current) return setError('That is the current code. Use Confirm instead.')
    if (reason.trim().length < 3) return setError('Give a reason of at least 3 characters.')
    setSaving(true); setError('')
    try {
      await api().put(`/doctor/visits/${visitId}/disease-code`, { code: picked.code, reason: reason.trim() })
      onDone(`Code changed to ${picked.code}.`)
    } catch (err) {
      setError(errorText(err, 'The code could not be changed.'))
      setSaving(false)
    }
  }

  return (
    <Modal open onClose={saving ? () => {} : onClose} title="Change disease code" size="lg">
      <div className="space-y-3">
        {error && <Alert type="error">{error}</Alert>}
        <label className="relative block">
          <span className="sr-only">Search codes</span>
          <Search size={14} className="absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
          <input value={query} onChange={e => setQuery(e.target.value)} placeholder="Search by code or condition, e.g. J18 or pneumonia"
            className="w-full pl-9 pr-3 py-2 text-sm border border-slate-200 rounded-lg bg-white text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500" />
        </label>
        <div className="max-h-56 overflow-y-auto border border-slate-200 rounded-lg" role="listbox" aria-label="Disease codes">
          {loading ? <p className="p-3 text-sm text-slate-500 flex items-center gap-2"><Loader2 size={14} className="animate-spin" /> Loading…</p>
            : codes.length === 0 ? <p className="p-3 text-sm text-slate-500">No code matches "{query}".</p>
            : codes.map(c => (
              <button key={c.code} type="button" role="option" aria-selected={picked?.code === c.code} onClick={() => setPicked(c)}
                className={`w-full text-left px-3 py-2 text-sm border-b border-slate-100 last:border-0 ${picked?.code === c.code ? 'bg-blue-50 text-blue-900' : 'hover:bg-slate-50 text-slate-800'}`}>
                <span className="font-mono font-semibold mr-2">{c.code}</span>{c.name}
              </button>
            ))}
        </div>
        <label className="flex flex-col gap-1 text-sm">
          <span className="font-medium text-slate-700">Reason for the change</span>
          <textarea rows={2} maxLength={500} value={reason} onChange={e => setReason(e.target.value)}
            placeholder="e.g. NS1 antigen positive; clinical picture consistent with dengue"
            className="w-full px-3 py-2 text-sm border border-slate-200 rounded-lg bg-white text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500" />
        </label>
        <div className="flex justify-end gap-2">
          <Button variant="secondary" onClick={onClose} disabled={saving}>Cancel</Button>
          <Button onClick={save} loading={saving}>Record change</Button>
        </div>
      </div>
    </Modal>
  )
}

export default function DiseaseCodePanel({ api, visitId }) {
  const [state, setState]   = useState({ status: 'loading', data: null, error: '' })
  const [notice, setNotice] = useState('')
  const [busy, setBusy]     = useState(false)
  const [actionError, setActionError] = useState('')
  const [changing, setChanging] = useState(false)

  const load = useCallback(async () => {
    setState(s => ({ ...s, status: 'loading', error: '' }))
    try {
      const res = await api().get(`/doctor/visits/${visitId}/disease-code`)
      setState({ status: 'ready', data: res.data.data, error: '' })
    } catch (err) {
      setState({ status: 'error', data: null, error: errorText(err, 'The disease code could not be loaded.') })
    }
  }, [api, visitId])

  useEffect(() => { load() }, [load])

  if (state.status === 'loading') return <Card className="p-8 flex justify-center"><Loader2 size={18} className="animate-spin text-slate-400" /></Card>
  if (state.status === 'error') return <Alert type="error">{state.error} <button className="underline ml-1" onClick={load}>Retry</button></Alert>

  const record = state.data
  const provisional = [...(record.history || [])].reverse().find(h => h.action === 'PROVISIONAL')
  const doctorEntry = [...(record.history || [])].reverse().find(h => h.action !== 'PROVISIONAL')
  const aiCodes = provisional?.aiSuggestedCodes || []

  const confirm = async () => {
    setBusy(true); setActionError(''); setNotice('')
    try {
      await api().put(`/doctor/visits/${visitId}/disease-code`, { code: record.currentCode })
      setNotice(`Code ${record.currentCode} confirmed.`)
      await load()
    } catch (err) {
      setActionError(errorText(err, 'The code could not be confirmed.'))
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className="space-y-4">
      {notice && <Alert type="success">{notice}</Alert>}
      {actionError && <Alert type="error">{actionError}</Alert>}

      <AiPanel analysis={record.analysis} analysisError={record.analysisError} />

      <Card className="p-5">
        <div className="flex flex-wrap items-start justify-between gap-3">
          <div>
            <p className="text-xs text-slate-500 uppercase tracking-wide font-medium">Disease code (ICD-10)</p>
            {record.currentCode ? (
              <p className="text-lg font-semibold text-slate-900 dark:text-slate-100">
                <span className="font-mono">{record.currentCode}</span> <span className="font-normal text-base">{record.currentName}</span>
              </p>
            ) : <p className="text-sm text-slate-500">No code assigned yet.</p>}
            <div className="mt-1"><CodeStatusPill status={record.status} /></div>
          </div>
          <div className="flex gap-2">
            {record.currentCode && record.status !== 'CONFIRMED' && (
              <Button variant="success" size="md" className="px-4 py-2.5 text-sm" loading={busy} onClick={confirm}><Check size={14} /> Confirm code</Button>
            )}
            <Button variant="secondary" onClick={() => setChanging(true)} disabled={busy}><Pencil size={14} /> {record.currentCode ? 'Change code' : 'Assign code'}</Button>
          </div>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4 pt-4 border-t border-slate-200 text-sm">
          <div>
            <p className="text-xs text-slate-500 uppercase tracking-wide font-medium">Matched from symptoms</p>
            <p>{provisional ? <><span className="font-mono font-semibold">{provisional.newCode}</span> {provisional.name}</> : '—'}</p>
          </div>
          <div>
            <p className="text-xs text-slate-500 uppercase tracking-wide font-medium">AI suggested</p>
            <p className="font-mono">{aiCodes.length ? aiCodes.join(', ') : <span className="font-sans text-slate-500">none</span>}</p>
          </div>
          <div>
            <p className="text-xs text-slate-500 uppercase tracking-wide font-medium">Doctor's code</p>
            {doctorEntry && (!provisional || doctorEntry.seq > provisional.seq) ? (
              <p>
                <span className="font-mono font-semibold">{doctorEntry.newCode}</span> {doctorEntry.name}
                {aiCodes.length > 0 && (
                  <span className={`block text-xs ${doctorEntry.matchesAiSuggestion ? 'text-emerald-600' : 'text-amber-600'}`}>
                    {doctorEntry.matchesAiSuggestion ? 'Matches an AI suggestion' : 'Differs from the AI suggestions'}
                  </span>
                )}
              </p>
            ) : <p className="text-slate-500">Not recorded yet</p>}
          </div>
        </div>
      </Card>

      <Card className="p-5">
        <p className="text-xs text-slate-500 uppercase tracking-wide font-medium mb-3">Code history — every entry is a ledger transaction; nothing is overwritten</p>
        <DiseaseCodeHistory record={record} />
      </Card>

      {changing && (
        <ChangeModal api={api} visitId={visitId} current={record.currentCode}
          onClose={() => setChanging(false)}
          onDone={async (msg) => { setChanging(false); setNotice(msg); await load() }} />
      )}
    </div>
  )
}
