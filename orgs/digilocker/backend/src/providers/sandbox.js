'use strict';

const crypto = require('crypto');

// ─────────────────────────────────────────────────────────────────────────────
// Sandbox DigiLocker provider.
//
// A self-contained simulator of the OAuth + issued-documents flow. It makes no
// external calls and every document it serves is a generated sample that says
// so on its face. It exists so the whole pull → encrypt → IPFS → Fabric path
// can be exercised without DigiLocker partner credentials.
// ─────────────────────────────────────────────────────────────────────────────

const CATALOGUE = [
  { slug: 'cbc-report',       name: 'Complete Blood Count Report',  docType: 'LAB_REPORT',        issuerId: 'sandbox.lab',       issuer: 'Sandbox Diagnostics Lab',  issuedAt: '2026-08-14' },
  { slug: 'lipid-profile',    name: 'Lipid Profile Report',         docType: 'LAB_REPORT',        issuerId: 'sandbox.lab',       issuer: 'Sandbox Diagnostics Lab',  issuedAt: '2026-09-02' },
  { slug: 'opd-prescription', name: 'OPD Prescription',             docType: 'PRESCRIPTION',      issuerId: 'sandbox.hospital',  issuer: 'Sandbox Health Centre',    issuedAt: '2026-09-03' },
  { slug: 'discharge',        name: 'Discharge Summary',            docType: 'DISCHARGE_SUMMARY', issuerId: 'sandbox.hospital',  issuer: 'Sandbox Health Centre',    issuedAt: '2026-06-21' },
  { slug: 'immunization',     name: 'Immunization Certificate',     docType: 'IMMUNIZATION',      issuerId: 'sandbox.health',    issuer: 'Sandbox Health Authority', issuedAt: '2025-11-30' },
];

const pdfEscape = (text) => String(text).replace(/[\\()]/g, '\\$&').replace(/[^\x20-\x7e]/g, '?');

// Builds a small, valid single-page PDF from text lines.
function buildPdf(lines) {
  const content = ['BT', '/F1 12 Tf', '72 760 Td', '16 TL']
    .concat(lines.map(line => `(${pdfEscape(line)}) Tj T*`))
    .concat(['ET'])
    .join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let body = '%PDF-1.4\n';
  const offsets = [];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(body, 'latin1'));
    body += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefAt = Buffer.byteLength(body, 'latin1');
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach(offset => { body += `${String(offset).padStart(10, '0')} 00000 n \n`; });
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefAt}\n%%EOF\n`;
  return Buffer.from(body, 'latin1');
}

function renderSample(entry, holderRef) {
  return buildPdf([
    'SANDBOX SAMPLE - NOT A REAL DOCUMENT',
    'Generated by the EHR DigiLocker sandbox simulator for integration testing.',
    '',
    `Document : ${entry.name}`,
    `Issuer   : ${entry.issuer}`,
    `Issued   : ${entry.issuedAt}`,
    `Holder   : sandbox holder ${holderRef}`,
    '',
    'This file contains no clinical information and has no legal validity.',
  ]);
}

class SandboxProvider {
  constructor({ publicUrl, signingKey }) {
    this.mode = 'sandbox';
    this.publicUrl = publicUrl;
    this.signingKey = signingKey;
  }

  sign(value) {
    return crypto.createHmac('sha256', this.signingKey).update(value).digest('base64url');
  }

  // A sandbox "account" is derived from the linking patient so two patients
  // never share sample documents.
  holderRef(subject) {
    return this.sign(`holder:${subject}`).slice(0, 10).toUpperCase();
  }

  authorizeUrl({ state }) {
    return `${this.publicUrl}/sandbox/authorize?state=${encodeURIComponent(state)}`;
  }

  // Called by the simulator's consent page when the holder clicks "Allow".
  issueCode(state) {
    const payload = Buffer.from(JSON.stringify({ state, exp: Date.now() + 120_000 })).toString('base64url');
    return `${payload}.${this.sign(`code:${payload}`)}`;
  }

  async exchangeCode({ code, state, subject }) {
    const [payload, signature] = String(code || '').split('.');
    const expected = this.sign(`code:${payload}`);
    const valid = signature && signature.length === expected.length &&
      crypto.timingSafeEqual(Buffer.from(signature), Buffer.from(expected));
    if (!valid) throw Object.assign(new Error('Invalid authorization code'), { status: 400, retryable: false });
    const claims = JSON.parse(Buffer.from(payload, 'base64url').toString('utf8'));
    if (claims.state !== state || claims.exp < Date.now()) {
      throw Object.assign(new Error('Authorization code expired or does not match this request'), { status: 400, retryable: false });
    }
    const ref = this.holderRef(subject);
    return {
      tokens: { accessToken: `sbx.${ref}.${this.sign(`token:${ref}`)}`, refreshToken: null, expiresAt: Date.now() + 3600_000 },
      account: { label: 'Sandbox holder', maskedId: `SBX-****-${ref.slice(-4)}` },
    };
  }

  holderFromTokens(tokens) {
    const [prefix, ref, signature] = String(tokens?.accessToken || '').split('.');
    if (prefix !== 'sbx' || !ref || signature !== this.sign(`token:${ref}`)) {
      throw Object.assign(new Error('DigiLocker session is no longer valid. Link again.'), { status: 401, code: 'RELINK_REQUIRED', retryable: false });
    }
    return ref;
  }

  async refresh(tokens) { return tokens; }

  async listIssued(tokens) {
    const ref = this.holderFromTokens(tokens);
    return CATALOGUE.map(entry => ({
      uri:      `sandbox-${entry.slug}-${ref}`,
      name:     entry.name,
      docType:  entry.docType,
      issuerId: entry.issuerId,
      issuer:   entry.issuer,
      issuedAt: entry.issuedAt,
      mime:     'application/pdf',
      size:     renderSample(entry, ref).length,
    }));
  }

  async fetchFile(tokens, uri) {
    const ref = this.holderFromTokens(tokens);
    const entry = CATALOGUE.find(item => uri === `sandbox-${item.slug}-${ref}`);
    if (!entry) throw Object.assign(new Error('Document not found in this DigiLocker account'), { status: 404, retryable: false });
    return { buffer: renderSample(entry, ref), mime: 'application/pdf', name: entry.name, docType: entry.docType, issuerId: entry.issuerId, issuer: entry.issuer, issuedAt: entry.issuedAt };
  }

  async revoke() { /* nothing to revoke upstream */ }
}

module.exports = { SandboxProvider, buildPdf };
