"""
Pydantic v2 data models for Clinical AI Agent.
Enforces strict typing, field validation, and structured error reporting.
"""

from datetime import datetime
from typing import Dict, List, Optional, Literal, Any
from pydantic import BaseModel, Field, field_validator
import re

class VitalSignInput(BaseModel):
    """Input payload for recording new vital signs."""
    blood_pressure: Optional[str] = Field(None, examples=["120/80 mmHg"], description="Systolic/Diastolic in mmHg")
    heart_rate: Optional[str] = Field(None, examples=["72 bpm"], description="Resting heart rate")
    blood_sugar: Optional[str] = Field(None, examples=["95 mg/dL"], description="Fasting or random blood glucose")
    weight: Optional[str] = Field(None, examples=["70 kg"], description="Patient body weight")
    height: Optional[str] = Field(None, examples=["175 cm"], description="Patient height")
    bmi: Optional[str] = Field(None, examples=["22.9"], description="Body Mass Index")
    temperature: Optional[str] = Field(None, examples=["98.6°F"], description="Body temperature")
    oxygen_saturation: Optional[str] = Field(None, examples=["98%"], description="SpO2 percentage")

    def to_measurement_dict(self) -> Dict[str, str]:
        """Convert non-null fields to standard clinical key-value pairs."""
        data = {}
        if self.blood_pressure: data["Blood Pressure"] = self.blood_pressure.strip()
        if self.heart_rate: data["Heart Rate"] = self.heart_rate.strip()
        if self.blood_sugar: data["Blood Sugar"] = self.blood_sugar.strip()
        if self.weight: data["Weight"] = self.weight.strip()
        if self.height: data["Height"] = self.height.strip()
        if self.bmi: data["BMI"] = self.bmi.strip()
        if self.temperature: data["Temperature"] = self.temperature.strip()
        if self.oxygen_saturation: data["Oxygen Saturation"] = self.oxygen_saturation.strip()
        return data

class MeasurementSnapshot(BaseModel):
    """Historical timestamped measurement snapshot."""
    timestamp: str
    data: Dict[str, str]

class PatientCreate(BaseModel):
    """Payload to register a new patient."""
    patient_id: str = Field(..., min_length=2, max_length=64, examples=["P001"])
    name: str = Field(..., min_length=1, max_length=120, examples=["John Doe"])
    age: int = Field(..., ge=0, le=130, examples=[45])
    gender: Literal["Male", "Female", "Other"] = Field(..., examples=["Male"])
    initial_vitals: Optional[VitalSignInput] = None

    @field_validator("patient_id")
    @classmethod
    def validate_patient_id(cls, v: str) -> str:
        clean = v.strip()
        if not re.match(r"^[A-Za-z0-9_\-]+$", clean):
            raise ValueError("patient_id must contain only alphanumeric characters, dashes, or underscores.")
        return clean

class PatientRecord(BaseModel):
    """Complete patient profile representation."""
    patient_id: str
    name: str
    age: int
    gender: str
    created_at: str
    measurements: List[MeasurementSnapshot] = []

class ClinicalRiskAlert(BaseModel):
    """Clinical safety alert generated by the deterministic rule engine."""
    parameter: str = Field(..., examples=["Blood Pressure"])
    severity: Literal["CRITICAL", "WARNING", "INFO"] = Field(..., examples=["WARNING"])
    value: str = Field(..., examples=["160/95 mmHg"])
    message: str = Field(..., examples=["Stage 2 Hypertension detected."])
    recommendation: str = Field(..., examples=["Consult attending physician for antihypertensive evaluation."])

class TrendAnalysisResult(BaseModel):
    """Result of clinical trajectory analysis over historical vital records."""
    patient_id: str
    total_snapshots: int
    status: Literal["STABLE", "MONITORING_REQUIRED", "CRITICAL_ACTION_REQUIRED"]
    alerts: List[ClinicalRiskAlert] = []
    latest_vitals: Dict[str, str] = {}
    historical_trajectory: Dict[str, List[Dict[str, Any]]] = {}

class AgentQueryRequest(BaseModel):
    """Request payload for Clinical RAG inference."""
    question: str = Field(..., min_length=2, examples=["What are the clinical targets for Type 2 Diabetes?"])
    patient_id: Optional[str] = Field(None, examples=["P001"], description="Optional patient to contextualize vitals.")

class AgentQueryResponse(BaseModel):
    """Response payload from Clinical RAG inference."""
    question: str
    answer: str
    confidence: Literal["High", "Medium", "Low"]
    sources: List[str] = []
    clinical_alerts: List[ClinicalRiskAlert] = []

class LabReportAnalysisRequest(BaseModel):
    """Payload to analyze unstructured or semi-structured laboratory reports."""
    patient_id: str = Field(..., examples=["P001"])
    report_text: str = Field(..., min_length=10, examples=["Complete Blood Count: WBC: 14.5, Platelets: 250k, Hb: 13.2 g/dL"])
    report_type: Optional[str] = Field("General Lab Report", examples=["Hematology Panel"])

class LabReportAnalysisResponse(BaseModel):
    """Structured insight output from lab report analysis."""
    patient_id: str
    report_type: str
    findings: List[str]
    abnormalities_flagged: List[str]
    suggested_followups: List[str]
    provenance_hash: str
